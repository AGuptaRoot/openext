export const classifyNiche = (prompt: string): IndustryPlaybook => {
  const text = prompt || '';
  for (const playbook of INDUSTRY_PLAYBOOKS) {
    if (playbook.id === 'default') continue;
    if (playbook.match.test(text)) return playbook;
  }
  return INDUSTRY_PLAYBOOKS.find((p) => p.id === 'default')!;
};

export const getPlaybookById = (id: string): IndustryPlaybook =>
  INDUSTRY_PLAYBOOKS.find((p) => p.id === id) ||
  INDUSTRY_PLAYBOOKS.find((p) => p.id === 'default')!;
